import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { SLOT_DIR } from "../agent/scaffold/roster-config.js";

export interface CodeFingerprintSpec {
  readonly roots: readonly string[];
  readonly excludedDirs: readonly string[];
  readonly excludedFiles: readonly string[];
  readonly extraFiles: readonly string[];
  readonly extraDirs: readonly string[];
}

function isRuntimeCodeFile(relPath: string, spec: CodeFingerprintSpec): boolean {
  if (spec.excludedFiles.includes(relPath)) return false;
  if (relPath === "instructions.md" || relPath.endsWith("/instructions.md")) return true;
  if (!relPath.endsWith(".ts")) return false;
  if (relPath.endsWith(".d.ts")) return false;
  if (relPath.endsWith("docs-generated.ts")) return false;
  if (relPath.endsWith("-test.ts") || relPath.endsWith(".test.ts") || relPath.endsWith(".spec.ts")) return false;
  return true;
}

export function codeFingerprintFiles(root: string, spec: CodeFingerprintSpec): readonly string[] {
  const excluded = new Set(spec.excludedDirs);
  const found = new Set<string>();
  const walk = (dir: string): void => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const abs = join(dir, entry.name);
      const rel = relative(root, abs).split(sep).join("/");
      if (entry.isDirectory()) {
        if (entry.name === "node_modules" || entry.name === "dist" || excluded.has(rel)) continue;
        walk(abs);
      } else if (entry.isFile() && isRuntimeCodeFile(rel, spec)) {
        found.add(rel);
      }
    }
  };
  for (const rootDir of spec.roots) {
    const abs = join(root, rootDir);
    try {
      if (!statSync(abs).isDirectory()) continue;
    } catch {
      continue;
    }
    walk(abs);
  }
  for (const rel of spec.extraFiles) {
    try {
      if (statSync(join(root, rel)).isFile()) found.add(rel);
    } catch {
    }
  }
  for (const dir of spec.extraDirs) {
    let entries;
    try {
      entries = readdirSync(join(root, dir), { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (entry.isFile()) found.add(`${dir}/${entry.name}`);
    }
  }
  return [...found].sort();
}

export function computeCodeFingerprint(root: string, spec: CodeFingerprintSpec): string {
  const digest = createHash("sha256");
  for (const rel of codeFingerprintFiles(root, spec)) {
    digest.update(rel);
    digest.update("\0");
    digest.update(createHash("sha256").update(readFileSync(join(root, rel))).digest());
    digest.update("\n");
  }
  return digest.digest("hex").slice(0, 16);
}

export const APP_CODE_FINGERPRINT_MODULE = "lib/app-code-fingerprint.generated.ts";

export function appCodeFingerprintSpec(agentDir: string): CodeFingerprintSpec {
  return {
    roots: [agentDir],
    excludedDirs: [`${agentDir}/memory/config/domains`, ...Object.values(SLOT_DIR).map((d) => `${agentDir}/${d}`)],
    excludedFiles: [`${agentDir}/lib/providers.generated.ts`, `${agentDir}/${APP_CODE_FINGERPRINT_MODULE}`],
    extraFiles: ["roster.config.ts", "roster.lock.json"],
    extraDirs: ["patches"],
  };
}

export function appCodeFiles(appRoot: string, agentDir: string): readonly string[] {
  return codeFingerprintFiles(appRoot, appCodeFingerprintSpec(agentDir));
}

export function computeAppCodeFingerprint(appRoot: string, agentDir: string): string {
  return computeCodeFingerprint(appRoot, appCodeFingerprintSpec(agentDir));
}

export function renderAppCodeFingerprintModule(fingerprint: string): string {
  return [
    "// GENERATED by `oe build` — DO NOT EDIT, AND DO NOT COMMIT (it is gitignored).",
    "// The hash of this app's runtime code (packages/core/scripts/code-fingerprint.ts, OPE-2466).",
    "// `lib/providers.generated.ts` imports this module, so it registers at boot. When the value differs",
    "// from the one a standing seat or work session was last served with, that generation retires.",
    "",
    'import { registerAppCodeFingerprint } from "@open-everywhere/core/agent/channels/app-code-fingerprint.js";',
    "",
    `registerAppCodeFingerprint(${JSON.stringify(fingerprint)});`,
    "",
  ].join("\n");
}

export function writeAppCodeFingerprint(appRoot: string, agentDir: string): { readonly fingerprint: string; readonly wrote: boolean; readonly path: string } {
  const fingerprint = computeAppCodeFingerprint(appRoot, agentDir);
  const path = `${agentDir}/${APP_CODE_FINGERPRINT_MODULE}`;
  const outFile = join(appRoot, path);
  const next = renderAppCodeFingerprintModule(fingerprint);
  let current: string | undefined;
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    current = undefined;
  }
  if (current === next) return { fingerprint, wrote: false, path };
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next, "utf8");
  return { fingerprint, wrote: true, path };
}
