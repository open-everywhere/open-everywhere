import { readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFileIfChanged } from "./write-if-changed.js";
import { workerOnlyTools } from "@open-everywhere/core/agent/access/worker-capabilities.js";
import { checkWorkerCapabilityGroups } from "@open-everywhere/core/agent/access/worker-capabilities.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const target = join(root, "packages", "core", "agent", "access", "worker-capability-index.generated.ts");

function renderList(name: string, doc: string, names: readonly string[]): string {
  return `${doc}\nexport const ${name}: readonly string[] = [\n${names.map((n) => `  ${JSON.stringify(n)},\n`).join("")}];\n`;
}

const banner =
  `// GENERATED by \`npx tsx scripts/worker-capability-index-generate.ts\` (also run by\n` +
  `// \`npm run docs:generate\`) from packages/core/agent/access/window-gate-manifest.ts — DO NOT\n` +
  `// HAND-EDIT. \`npm run lint:capabilities\` (chained into \`npm run lint:docs\`, which is in the\n` +
  `// test chain) fails the build if this file and the posture tables ever disagree.\n` +
  `//\n` +
  `// WHAT THIS IS: the tools a one-shot \`task\` WORKER mounts that a conversational seat does not —\n` +
  `// i.e. exactly the capability a seat gains by delegating. agent/access/worker-capabilities.ts\n` +
  `// groups these by capability and renders them into the seat's standing instructions, so a seat\n` +
  `// that can only talk and delegate still knows what it is able to route. See that file's header\n` +
  `// and scripts/worker-capability-index-generate.ts for why the facts are generated and the prose\n` +
  `// is not.\n` +
  `//\n` +
  `// 🔴 A GROWING LIST HERE IS A CAPABILITY MOVING OFF THE SEAT. Read the diff as such: every name\n` +
  `// added is a verb a conversational seat can no longer call directly, and every name removed is\n` +
  `// one it can. That is the review this file exists for.\n`;

const problems = checkWorkerCapabilityGroups();
if (problems.length > 0) {
  console.error("worker-capability grouping is not total over the window-gate surface:");
  for (const p of problems) console.error(`  • ${p}`);
  process.exit(1);
}

const standing = workerOnlyTools("standing");
const thread = workerOnlyTools("thread");

const body =
  `${banner}\n` +
  renderList(
    "WORKER_ONLY_TOOLS_STANDING",
    "/** Worker-only tools as seen from a STANDING seat (a channel root, a unified window, a DM root). */",
    standing,
  ) +
  `\n` +
  renderList(
    "WORKER_ONLY_TOOLS_THREAD",
    "/** Worker-only tools as seen from a THREAD seat. Identical to the standing list wherever the two\n *  grains differ only on grain-lifecycle verbs, which the index excludes by design\n *  (agent/access/worker-capabilities.ts WORKER_INDEX_LIFECYCLE). */",
    thread,
  );

if (check) {
  if (!existsSync(target)) {
    console.error(`worker-capability index is MISSING: ${target}\nRun \`npm run capabilities:generate\` and commit the result.`);
    process.exit(1);
  }
  if (readFileSync(target, "utf8") !== body) {
    console.error(
      `worker-capability index is STALE: packages/core/agent/access/worker-capability-index.generated.ts no longer matches the window-gate posture tables.\n` +
        `Run \`npm run capabilities:generate\` (or \`npm run docs:generate\`) and commit the regenerated file — and READ the diff: a name appearing there is a capability that just left the conversational seat.`,
    );
    process.exit(1);
  }
  console.log(`✓ worker-capability index is current (${standing.length} worker-only tool(s) from a standing seat, ${thread.length} from a thread seat)`);
} else {
  const wrote = writeFileIfChanged(target, body);
  console.log(
    `✓ ${wrote ? "wrote" : "already current"}: packages/core/agent/access/worker-capability-index.generated.ts ` +
      `(${standing.length} standing / ${thread.length} thread worker-only tools)`,
  );
}
