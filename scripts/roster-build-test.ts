import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

let n = 0;
const ok = (cond: boolean, label: string): void => {
  assert.ok(cond, label);
  n++;
};
const eq = <T>(actual: T, expected: T, label: string): void => {
  assert.deepEqual(actual, expected, label);
  n++;
};

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CLI = join(REPO, "packages/core/scripts/oe-cli.ts");
const TSX_CLI = join(REPO, "node_modules/tsx/dist/cli.mjs");

const root = mkdtempSync(join(tmpdir(), "oe-roster-"));
const write = (rel: string, body: string): void => {
  const abs = join(root, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, body);
};
const read = (rel: string): string => readFileSync(join(root, rel), "utf8");

function oe(...args: string[]): { code: number; out: string } {
  try {
    const out = execFileSync(process.execPath, [TSX_CLI, CLI, "build", ...args], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    return { code: 0, out };
  } catch (err) {
    const e = err as { status?: number; stdout?: string; stderr?: string };
    return { code: e.status ?? 1, out: `${e.stdout ?? ""}${e.stderr ?? ""}` };
  }
}

write("package.json", JSON.stringify({ name: "fixture-app", private: true, type: "module" }, null, 2));

function fixturePackage(name: string, manifest: unknown, modules: readonly string[]): void {
  write(`node_modules/${name}/package.json`, JSON.stringify({ name, version: "9.9.9", type: "module" }, null, 2));
  write(`node_modules/${name}/agent/contributions.js`, `export const CONTRIBUTIONS = ${JSON.stringify(manifest, null, 2)};\n`);
  for (const m of modules) write(`node_modules/${name}/${m}`, "export default {};\n");
}

fixturePackage(
  "@fixture/alpha",
  {
    schemaVersion: 1,
    package: "@fixture/alpha",
    contributions: [
      { kind: "tool", name: "alpha_tool", module: "agent/tools/alpha_tool.js", summary: "Do an alpha thing." },
      { kind: "tool", name: "declined_tool", module: "agent/tools/declined_tool.js", summary: "Do a risky thing." },
      { kind: "hook", name: "alpha-hook", module: "agent/hooks/alpha-hook.js" },
    ],
  },
  ["agent/tools/alpha_tool.js", "agent/tools/declined_tool.js", "agent/hooks/alpha-hook.js"],
);

fixturePackage(
  "@fixture/beta",
  {
    schemaVersion: 1,
    package: "@fixture/beta",
    contributions: [{ kind: "channel", name: "beta", module: "agent/channels/beta.js" }],
  },
  ["agent/channels/beta.js"],
);

write(
  "roster.config.ts",
  `export default {
  packages: {
    "@fixture/alpha": { exclude: { declined_tool: "this deployment does not want the risky thing" } },
    "@fixture/beta": true,
  },
};
`,
);

{
  const r = oe();
  eq(r.code, 1, "a first build with no lock is refused");
  ok(r.out.includes("UNREVIEWED"), "…because every contribution is UNREVIEWED");
  ok(r.out.includes("Do an alpha thing."), "…and the summary is quoted so a human can judge it");
  ok(r.out.includes("oe build --accept"), "…and the red names the one command that clears it");
  ok(!existsSync(join(root, "agent/tools/alpha_tool.ts")), "NOTHING is written while the verdict is not clean");
}

{
  const r = oe("--accept");
  eq(r.code, 0, "--accept writes the lock and builds");
  ok(existsSync(join(root, "roster.lock.json")), "the lock is written");
  const lock = JSON.parse(read("roster.lock.json")) as { packages: Record<string, { contributions: Record<string, string> }> };
  eq(lock.packages["@fixture/alpha"]!.contributions["tool/declined_tool"], "excluded", "an exclusion is recorded in the lock, not merely absent");
  eq(lock.packages["@fixture/alpha"]!.contributions["tool/alpha_tool"], "mounted", "a mount is recorded too");

  eq(
    read("agent/tools/alpha_tool.ts"),
    '// GENERATED by `oe build` from roster.config.ts — DO NOT EDIT.\nexport { default } from "@fixture/alpha/agent/tools/alpha_tool.js";\n',
    "the mounted shim is the header plus the re-export",
  );
  ok(existsSync(join(root, "agent/hooks/alpha-hook.ts")), "hooks materialise into their own slot dir");
  ok(existsSync(join(root, "agent/channels/beta.ts")), "a second package's channel materialises");
  ok(!existsSync(join(root, "agent/tools/declined_tool.ts")), "an EXCLUDED contribution has no file — the lock is where the decision lives");
  ok(existsSync(join(root, "agent/lib/providers.generated.ts")), "the provider table is always emitted, even with no providers");
  eq(readdirSync(join(root, "agent/connections")).length, 0, "an owned slot dir with nothing planned exists and is empty");
  eq(oe("--check").code, 0, "a freshly built tree passes --check");
}

{
  write("agent/tools/alpha_tool.ts", "export default 'tampered';\n");
  const check = oe("--check");
  eq(check.code, 1, "a hand-edited generated file fails --check");
  ok(check.out.includes("DRIFTED · agent/tools/alpha_tool.ts"), "…naming the exact path");
  eq(oe().code, 0, "a plain build reconciles it");
  ok(read("agent/tools/alpha_tool.ts").includes("@fixture/alpha/agent/tools/alpha_tool.js"), "…back to the planned content");
}

{
  write("agent/tools/smuggled.ts", "export default {};\n");
  const check = oe("--check");
  eq(check.code, 1, "an unplanned file in an owned slot dir fails --check");
  ok(check.out.includes("STRAY · agent/tools/smuggled.ts"), "…naming it as a STRAY");
  eq(oe().code, 0, "a plain build reconciles it");
  ok(!existsSync(join(root, "agent/tools/smuggled.ts")), "…by deleting it — a smuggled tool cannot survive a build");
  write("agent/lib/authored.ts", "export const authored = true;\n");
  eq(oe().code, 0, "a build with an authored agent/lib sibling succeeds");
  ok(existsSync(join(root, "agent/lib/authored.ts")), "agent/lib is NOT an owned directory — authored files there survive");
}

{
  rmSync(join(root, "agent/hooks/alpha-hook.ts"));
  const one = oe("--check");
  eq(one.code, 1, "an absent planned file fails --check");
  ok(one.out.includes("NOT BUILT · agent/hooks/alpha-hook.ts"), "…naming it as NOT BUILT");
  ok(!one.out.includes("DRIFTED · agent/hooks/alpha-hook.ts"), "…and never as DRIFTED");
  ok(one.out.includes("npm run build"), "…with the command that builds it");

  for (const dir of ["agent/tools", "agent/hooks", "agent/channels", "agent/connections"]) rmSync(join(root, dir), { recursive: true, force: true });
  rmSync(join(root, "agent/lib/providers.generated.ts"), { force: true });
  const none = oe("--check");
  eq(none.code, 1, "a tree that was never built fails --check");
  ok(/NOT BUILT · the slot tree is not built yet \(\d+ file\(s\)\)/.test(none.out), "…as ONE not-built line for the whole tree");
  ok(!none.out.includes("DRIFTED"), "…with no DRIFTED line");
  eq(oe().code, 0, "a plain build writes the tree");
  eq(oe("--check").code, 0, "…and --check passes again");
}

{
  const manifest = JSON.parse(read("node_modules/@fixture/alpha/agent/contributions.js").replace("export const CONTRIBUTIONS = ", "").replace(/;\n$/, "")) as {
    contributions: Record<string, unknown>[];
  };
  manifest.contributions.push({ kind: "tool", name: "shred_repo", module: "agent/tools/shred_repo.js", summary: "Delete a repository." });
  write("node_modules/@fixture/alpha/agent/contributions.js", `export const CONTRIBUTIONS = ${JSON.stringify(manifest, null, 2)};\n`);
  write("node_modules/@fixture/alpha/agent/tools/shred_repo.js", "export default {};\n");

  const r = oe();
  eq(r.code, 1, "an `npm update` that ships a new tool reds the build — no silent capability grant");
  ok(r.out.includes("shred_repo"), "…naming the new tool");
  ok(r.out.includes("Delete a repository."), "…and what it does");
  ok(!existsSync(join(root, "agent/tools/shred_repo.ts")), "…and it is NOT mounted meanwhile");

  const report = JSON.parse(oe("--json").out) as {
    verdict: string;
    packages: { name: string; unreviewed: { name: string; summary?: string }[] }[];
    suggestedConfigPatch: { path: string[]; op: string; valueHint: string }[];
    roster: { mounted: number; excluded: number; frameworkDisabled: number };
  };
  eq(oe("--json").code, 0, "--json exits 0 on `unreviewed` so the upgrade agent can consume it (the exit-code split is deliberate)");
  eq(report.verdict, "unreviewed", "…with the verdict in the payload");
  eq(report.packages.find((p) => p.name === "@fixture/alpha")!.unreviewed[0]!.summary, "Delete a repository.", "the summary is what the upgrade agent educates with");
  eq(report.suggestedConfigPatch[0]!.path, ["@fixture/alpha", "exclude", "shred_repo"], "the patch names the LOCATION; the agent owns the prose");
  ok(report.roster.mounted > 0, "the report carries the roster counts");

  eq(oe("--accept").code, 0, "accepting it clears the red");
  ok(existsSync(join(root, "agent/tools/shred_repo.ts")), "…and only then does it mount");
}

{
  const before = read("node_modules/@fixture/beta/agent/contributions.js");
  write("node_modules/@fixture/beta/agent/contributions.js", `export const CONTRIBUTIONS = ${JSON.stringify({ schemaVersion: 1, package: "@fixture/beta", contributions: [] }, null, 2)};\n`);
  const r = oe();
  eq(r.code, 1, "a contribution disappearing from a manifest reds");
  ok(r.out.includes("VANISHED"), "…as VANISHED");
  ok(existsSync(join(root, "agent/channels/beta.ts")), "…and the tree is untouched until a human looks");
  write("node_modules/@fixture/beta/agent/contributions.js", before);
  eq(oe().code, 0, "restoring the manifest restores the green");
}

{
  const manifest = { schemaVersion: 1, package: "@fixture/beta", contributions: [{ kind: "channel", name: "beta", module: "agent/channels/ghost.js" }] };
  write("node_modules/@fixture/beta/agent/contributions.js", `export const CONTRIBUTIONS = ${JSON.stringify(manifest, null, 2)};\n`);
  rmSync(join(root, "agent/channels/beta.ts"), { force: true });
  const r = oe("--accept");
  eq(r.code, 1, "a manifest naming a module its package does not ship reds");
  ok(r.out.includes("do not resolve"), "…as an unresolvable planned import");
  ok(r.out.includes("@fixture/beta/agent/channels/ghost.js"), "…naming the exact specifier");
  ok(!existsSync(join(root, "agent/channels/beta.ts")), "…having written NOTHING");
}

{
  write(
    "node_modules/@fixture/beta/agent/contributions.js",
    `export const CONTRIBUTIONS = ${JSON.stringify({ schemaVersion: 1, package: "@fixture/beta", contributions: [{ kind: "channel", name: "beta", module: "agent/channels/beta.js" }] }, null, 2)};\n`,
  );
  rmSync(join(root, "agent/channels/beta.ts"), { force: true });
  const r = oe("--show");
  eq(r.code, 0, "--show succeeds");
  ok(r.out.includes("agent/channels/beta.ts"), "…printing each planned path");
  ok(r.out.includes('export { default } from "@fixture/beta/agent/channels/beta.js";'), "…with its full contents");
  ok(!existsSync(join(root, "agent/channels/beta.ts")), "…and writing nothing");
  const one = oe("--show", "agent/channels/beta.ts");
  ok(one.out.includes("agent/channels/beta.ts"), "--show <path> prints that one file");
  ok(!one.out.includes("alpha_tool"), "…and only that one");
}

{
  const good = read("roster.config.ts");
  write("roster.config.ts", good.replace('"this deployment does not want the risky thing"', '""'));
  const r = oe();
  eq(r.code, 1, "an exclusion with an empty reason is refused");
  ok(r.out.includes("empty reason"), "…naming the rule");
  write("roster.config.ts", good);
}

rmSync(root, { recursive: true, force: true });
console.log(`✓ roster-build-test: ${n} assertions passed (materialise, reconcile, delete strays, unreviewed/vanished, --show/--json/--accept)`);
