import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFileIfChanged } from "./write-if-changed.js";
import {
  checkIngestionSites,
  findIngestionSites,
  routeKey,
  type IngestionSite,
} from "@open-everywhere/core/agent/access/ingestion-binding-manifest.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const listOnly = process.argv.includes("--list");
const target = join(root, "packages", "core", "agent", "access", "ingestion-route-inventory.generated.ts");

function tsFilesUnder(dir: string): string[] {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return [];
  }
  const out: string[] = [];
  for (const name of entries) {
    if (name === "node_modules" || name === "dist" || name === "generated") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...tsFilesUnder(full));
    else if (name.endsWith(".ts") && !name.endsWith(".d.ts")) out.push(full);
  }
  return out;
}

const roots = [join(root, "packages", "core", "agent"), join(root, "agent")].filter((d) => {
  try {
    return statSync(d).isDirectory();
  } catch {
    return false;
  }
});
const providersDir = join(root, "packages", "providers");
try {
  for (const p of readdirSync(providersDir)) {
    const agentDir = join(providersDir, p, "agent");
    try {
      if (statSync(agentDir).isDirectory()) roots.push(agentDir);
    } catch {
    }
  }
} catch {
}

const files = roots.flatMap((r) => tsFilesUnder(r));
if (files.length === 0) {
  console.error(`✗ ingestion-binding-lint: found no sources under ${roots.map((r) => relative(root, r)).join(", ")} — refusing to report clean against an unread tree`);
  process.exit(1);
}

function relPosix(f: string): string {
  return relative(root, f).split(sep).join("/");
}

const sites: IngestionSite[] = files.flatMap((f) => findIngestionSites(relPosix(f), readFileSync(f, "utf8")));

if (listOnly) {
  for (const s of [...sites].sort((a, b) => (a.file === b.file ? a.line - b.line : a.file.localeCompare(b.file)))) {
    const kind = s.kindLiteral ?? "‹MISSING›";
    console.log(`${(s.pending ? "PENDING" : kind).padEnd(18)} ${s.file}:${s.line}  ${s.form.padEnd(18)} label=${s.labelText ?? (s.hasLabel ? "‹dynamic›" : "‹MISSING›")}`);
  }
  console.log(`\n${sites.length} ingestion declaration site(s) over ${files.length} source file(s).`);
  process.exit(0);
}

const defects = checkIngestionSites(sites);
if (defects.length > 0) {
  console.error(`✗ ingestion-binding-lint: ${defects.length} problem(s) — a site that does not bind a literal, known IngestionKind, or carries no label:`);
  for (const d of defects) console.error(`  - [${d.rule}] ${d.file}:${d.line} — ${d.message}`);
  console.error(
    `\n  Why this is a hard error: a kind that is a variable, a typo, or missing compiles and runs — decideIngestion never throws (see\n` +
      `  access/taint-enforcement.ts's header) and classifyIngestion's switch falls through to \`undefined\` for anything not in\n` +
      `  INGESTION_KINDS, so the failure is silent unless a lint catches the literal itself.`,
  );
  process.exit(1);
}

function uniqueKeys(all: readonly IngestionSite[]): ReadonlyMap<IngestionSite, string> {
  const seen = new Map<string, number>();
  const out = new Map<IngestionSite, string>();
  for (const s of all) {
    const base = routeKey(s);
    const n = (seen.get(base) ?? 0) + 1;
    seen.set(base, n);
    out.set(s, n === 1 ? base : `${base}#${n}`);
  }
  return out;
}

const keys = uniqueKeys(sites);
const rows = [...sites]
  .map((s) => ({
    key: keys.get(s)!,
    file: s.file,
    form: s.form,
    kind: s.kindLiteral!,
    label: s.labelText ?? null,
    pending: s.pending,
  }))
  .sort((a, b) => a.key.localeCompare(b.key));

const banner =
  `// GENERATED by \`npx tsx scripts/ingestion-binding-lint.ts\` — DO NOT HAND-EDIT.\n` +
  `// \`npm run lint:ingestion\` (in the test chain) fails the build if this file no longer matches\n` +
  `// what packages/*/agent/ actually declares. This is the AUTHORITATIVE route inventory OPE-470's\n` +
  `// route-join sweep reads from — see packages/core/agent/access/ingestion-binding-manifest.ts for\n` +
  `// what a "route" is and the three rules a site must satisfy to appear here.\n` +
  `//\n` +
  `// A row appearing or disappearing is a read/connector/webhook/… surface gaining or losing its\n` +
  `// ingestion declaration — read the diff as that, the same way a worker-capability-index diff is\n` +
  `// read as a capability moving on or off the conversational seat.\n` +
  `//\n` +
  `// ⚠️ A \`form: "noteIngestionVerdict"\` row is an OBSERVER: it reports its kind to the table\n` +
  `// without governing the route's own \`ingestUntrusted\` call. Do not read such a row as "this\n` +
  `// route is table-governed" — the route's fence stands on its own and marks unconditionally.\n`;

function renderRow(r: (typeof rows)[number]): string {
  const label = r.label === null ? "null" : JSON.stringify(r.label);
  return `  { key: ${JSON.stringify(r.key)}, file: ${JSON.stringify(r.file)}, form: ${JSON.stringify(r.form)}, kind: ${JSON.stringify(r.kind)}, label: ${label}, pending: ${r.pending} },\n`;
}

const body =
  `${banner}\n` +
  `export interface IngestionRoute {\n` +
  `  /** Stable identity: file + label text (or an index suffix on a same-file collision). */\n` +
  `  readonly key: string;\n` +
  `  readonly file: string;\n` +
  `  readonly form: "ingestion-property" | "ingestion-const" | "noteIngestionVerdict" | "chatReadIngestion";\n` +
  `  readonly kind: string;\n` +
  `  /** The label's source text, or \`null\` when it is only a bare \`label\` shorthand property. */\n` +
  `  readonly label: string | null;\n` +
  `  /** \`kind: "TODO"\`, accepted because it carries a \`// TODO(ingestion): …\` comment — resolved OR removed before this may ship as a real gated route. */\n` +
  `  readonly pending: boolean;\n` +
  `}\n\n` +
  `export const INGESTION_ROUTES: readonly IngestionRoute[] = [\n${rows.map(renderRow).join("")}];\n`;

if (check) {
  let existing: string | undefined;
  try {
    existing = readFileSync(target, "utf8");
  } catch {
    existing = undefined;
  }
  if (existing === undefined) {
    console.error(`✗ ingestion-binding-lint: inventory is MISSING: ${relative(root, target)}\nRun \`npx tsx scripts/ingestion-binding-lint.ts\` and commit the result.`);
    process.exit(1);
  }
  if (existing !== body) {
    console.error(
      `✗ ingestion-binding-lint: inventory is STALE: ${relative(root, target)} no longer matches what packages/*/agent/ declares.\n` +
        `Run \`npx tsx scripts/ingestion-binding-lint.ts\` and commit the regenerated file — and READ the diff: a route appearing or\n` +
        `disappearing is an ingestion site gaining or losing its declaration.`,
    );
    process.exit(1);
  }
  const pending = rows.filter((r) => r.pending).length;
  console.log(`✓ lint:ingestion: ${rows.length} route(s) over ${files.length} source file(s), every one a literal known kind with a label (${pending} pending on a TODO(ingestion) marker) — inventory current`);
} else {
  const wrote = writeFileIfChanged(target, body);
  console.log(
    `✓ ${relative(root, target)} ${wrote ? "updated" : "already current"} (${rows.length} route(s) over ${files.length} source file(s))`,
  );
}
