import { readdirSync, readFileSync, existsSync, rmSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFileIfChanged } from "./write-if-changed.js";
import {
  checkDocsSourceMap,
  docSummaryOf,
  docTitleOf,
  isCompiledDoc,
  providerForDocPath,
  sectionForDocPath,
  UNCOMPILED_DOC_SECTIONS,
} from "@open-everywhere/core/agent/docs/source-map.js";

const rootFlagAt = process.argv.indexOf("--root");
const root =
  rootFlagAt >= 0 && process.argv[rootFlagAt + 1] !== undefined
    ? process.argv[rootFlagAt + 1]
    : join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const DOC_ENTRY_IMPORT = 'import type { DocEntry } from "@open-everywhere/core/agent/adapter-api.js";';

function banner(what: string): string {
  return (
    `// GENERATED by \`npx tsx scripts/docs-generate.ts\` from ${what} — DO NOT HAND-EDIT.\n` +
    `// Edit the markdown under docs/ and re-run the generator; \`npm run lint:docs\` fails the\n` +
    `// build if this file and its sources ever disagree. See scripts/docs-generate.ts for why the\n` +
    `// manual is compiled in at all (docs/ does not exist on disk in a hosted deployment).\n`
  );
}

function docPaths(): string[] {
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.isFile() && e.name.endsWith(".md")) out.push(relative(root, p).split("\\").join("/"));
    }
  };
  walk(join(root, "docs"));
  return out.sort();
}

function bundleIds(): string[] {
  return readdirSync(join(root, "packages", "providers"), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

function renderEntry(path: string, markdown: string): string {
  return (
    `  {\n` +
    `    path: ${JSON.stringify(path)},\n` +
    `    title: ${JSON.stringify(docTitleOf(path, markdown))},\n` +
    `    summary: ${JSON.stringify(docSummaryOf(markdown))},\n` +
    `    markdown: ${JSON.stringify(markdown)},\n` +
    `  },\n`
  );
}

function renderModule(what: string, exportName: string, paths: readonly string[], read: (p: string) => string): string {
  let body = "";
  for (const p of paths) body += renderEntry(p, read(p));
  return `${banner(what)}\n${DOC_ENTRY_IMPORT}\n\nexport const ${exportName}: readonly DocEntry[] = [\n${body}];\n`;
}

function renderIndex(sections: readonly string[]): string {
  const id = (s: string): string => `SECTION_${s.replace(/[^A-Za-z0-9]+/gu, "_").toUpperCase()}`;
  const imports = sections.map((s) => `import { ${id(s)} } from "./${s}.js";`).join("\n");
  const spreads = sections.map((s) => `  ...${id(s)},`).join("\n");
  return (
    `${banner("the docs/ tree")}\n` +
    `${DOC_ENTRY_IMPORT}\n${imports}\n\n` +
    `/** Every doc that is NOT one provider bundle's setup runbook — see scripts/docs-generate.ts. */\n` +
    `export const UNIVERSAL_DOCS: readonly DocEntry[] = [\n${spreads}\n];\n`
  );
}

const paths = docPaths();
const bundles = bundleIds();

const mapProblems = checkDocsSourceMap({ docPaths: paths, bundleIds: bundles });
if (mapProblems.length > 0) {
  console.error(`✗ docs source map (${mapProblems.length} problem(s)):`);
  for (const p of mapProblems) console.error(`  - ${p}`);
  process.exit(1);
}

const compiled = paths.filter(isCompiledDoc);

const read = (p: string): string => readFileSync(join(root, p), "utf8");
const universal = new Map<string, string[]>();
const perProvider = new Map<string, string[]>();
for (const p of compiled) {
  const provider = providerForDocPath(p, bundles);
  const bucket = provider === undefined ? universal : perProvider;
  const key = provider ?? sectionForDocPath(p);
  const list = bucket.get(key);
  if (list) list.push(p);
  else bucket.set(key, [p]);
}

const files = new Map<string, string>();
const sections = [...universal.keys()].sort();
for (const s of sections) {
  files.set(
    `agent/docs/generated/${s}.ts`,
    renderModule(`docs/${s === "root" ? "*.md" : `${s}/`}`, `SECTION_${s.replace(/[^A-Za-z0-9]+/gu, "_").toUpperCase()}`, universal.get(s)!, read),
  );
}
files.set("agent/docs/generated/index.ts", renderIndex(sections));
for (const [id, list] of [...perProvider.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  files.set(`packages/providers/${id}/agent/docs-generated.ts`, renderModule(list.join(", "), "PROVIDER_DOCS", list, read));
}

for (const id of bundles) {
  const reg = join(root, "packages", "providers", id, "agent", "register.ts");
  const src = existsSync(reg) ? readFileSync(reg, "utf8") : "";
  if (!/registerProviderDocs\s*\(/u.test(src)) {
    console.error(
      `✗ packages/providers/${id}/agent/register.ts never calls registerProviderDocs(...) — its runbook would be compiled in but never served. Add the call.`,
    );
    process.exit(1);
  }
}

const generatedDir = join(root, "agent", "docs", "generated");
const stale: string[] = [];
if (existsSync(generatedDir)) {
  for (const f of readdirSync(generatedDir)) {
    const rel = `agent/docs/generated/${f}`;
    if (!files.has(rel)) stale.push(rel);
  }
}
for (const id of readdirSync(join(root, "packages", "providers"), { withFileTypes: true }).filter((e) => e.isDirectory())) {
  const rel = `packages/providers/${id.name}/agent/docs-generated.ts`;
  if (!files.has(rel) && existsSync(join(root, rel))) stale.push(rel);
}

if (check) {
  const problems: string[] = [];
  for (const [rel, content] of files) {
    const abs = join(root, rel);
    if (!existsSync(abs)) {
      problems.push(`${rel} is missing`);
      continue;
    }
    if (readFileSync(abs, "utf8") !== content) problems.push(`${rel} is out of date`);
  }
  for (const rel of stale) problems.push(`${rel} is stale (no doc source maps to it)`);
  if (problems.length > 0) {
    console.error(`✗ generated docs are out of sync with docs/ (${problems.length} problem(s)):`);
    for (const p of problems) console.error(`  - ${p}`);
    console.error("  Run: npx tsx scripts/docs-generate.ts");
    process.exit(1);
  }
  console.log(
    `✓ docs registry in sync — ${compiled.length} docs (${[...perProvider.keys()].length} provider runbooks) across ${files.size} generated modules` +
      `${paths.length - compiled.length ? `, ${paths.length - compiled.length} not compiled (${UNCOMPILED_DOC_SECTIONS.join(", ")})` : ""}`,
  );
} else {
  let written = 0;
  for (const [rel, content] of files) {
    if (writeFileIfChanged(join(root, rel), content)) written++;
  }
  for (const rel of stale) rmSync(join(root, rel));
  console.log(
    `✓ ${files.size} generated modules for ${compiled.length} docs — ${written} written, ${files.size - written} already current` +
      `${paths.length - compiled.length ? `, ${paths.length - compiled.length} not compiled (${UNCOMPILED_DOC_SECTIONS.join(", ")})` : ""}` +
      `${stale.length ? ` (removed ${stale.length} stale)` : ""}`,
  );
}
