export const EXPECTED_OFFERED: Readonly<Record<SeatShape, readonly string[]>> = {
  ...ROWS,
  haltedWorker: ROWS.delegatedWorker,
  haltedWideSeatNoOneshot: ROWS.wideSeatNoOneshot.filter((n) => n !== "web_fetch"),
};

export function diffOffered(shape: SeatShape, offered: readonly string[], expected: readonly string[] = EXPECTED_OFFERED[shape]): string[] {
  const got = new Set(offered);
  const want = new Set(expected);
  const extra = [...got].filter((n) => !want.has(n)).sort();
  const missing = [...want].filter((n) => !got.has(n)).sort();
  return [
    ...extra.map((n) => `${shape}: offered "${n}", which the expected list does not hold`),
    ...missing.map((n) => `${shape}: did not offer "${n}", which the expected list holds`),
  ];
}

export function fileWritesOffered(shape: SeatShape, offered: readonly string[]): string[] {
  if (!READ_ONLY_SHAPES.has(shape)) return [];
  return FILE_WRITE_TOOLS.filter((n) => offered.includes(n)).map((n) => `${shape}: read-only seat offered file-write tool "${n}"`);
}
